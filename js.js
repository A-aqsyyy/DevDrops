let a = 10, b = 3;

a + b 
console.log(a+b);  // 13 - Addition
a - b  
console.log(a - b ); // 7  - Subtraction
a * b  
console.log(a *b );  // 30 - Multiplication
a / b  
console.log(a / b ); // 3.33 - Division
a % b 
console.log(a % b ); // 1  - Remainder (Modulus)

let x = 10;   // assign 10
x += 5;    
console.log(x += 5);   // x = x + 5 → 15
x -= 3;   
console.log(x -= 3);  // x = x - 3 → 12
x *= 2;   
console.log(x *= 2);    // x = x * 2 → 24




5 == "5"   
console.log(5 == "5" ); // true  → same value (loose)
5 === "5"   
console.log(5 === "5" );// false → different type (strict)
5 != 3     
console.log(5 != 3  ); // true
5 !== "5" 
console.log(5 !== "5" );  // true
5 > 3     
console.log(5 > 3   );  // true
5 < 3     
console.log(5 < 3  );  // false
5 >= 5    
console.log(5 >= 5  );  // true
5 <= 4  
console.log(5 <= 4 );    // false




true && false  
console.log(
true && false); // false → AND (both must be true)
true || false
console.log(true || false);   // true  → OR  (one must be true)
!true     
console.log(!true  );    // false → NOT (flips the value)





let n = 5;

n++  
console.log(n++ ); // returns 5, then n becomes 6 (post-increment)
++n  
console.log(++n  ); // n becomes 7, then returns 7 (pre-increment)
n--   
console.log(n-- );// returns 7, then n becomes 6 (post-decrement)
--n  
console.log(--n  ); // n becomes 5, then returns 5 (pre-decrement)


